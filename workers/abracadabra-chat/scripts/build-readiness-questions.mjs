// Copies the Readiness Check questions (prompt, options) from readiness-check/src/lib/assessment/config.v1.json
// into src/readiness-questions.js, so the chat asks the same questions the check scores.
// Step order and validation stay with the check: the chat follows the nextStep it returns.
// Run: npm run readiness
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
const config = JSON.parse(readFileSync(`${here}../../../readiness-check/src/lib/assessment/config.v1.json`, "utf8"));
const questions = {};
for (const q of config.questions) {
  questions[q.id] = {
    type: q.type,
    prompt: q.prompt,
    ...(q.options ? { options: q.options.map((o) => ({ value: o.value, label: o.label })) } : {}),
    ...(q.maxLength ? { maxLength: q.maxLength } : {}),
    ...(q.suggestions ? { suggestions: q.suggestions } : {}),
  };
}
const out = {
  version: config.meta?.version || "v1",
  questions,
  severity: config.severity.map((s) => ({ value: s.score, label: s.label })),
  bands: Object.fromEntries(config.bands.map((b) => [b.id, { label: b.label, sentence: b.sentence }])),
};
writeFileSync(
  `${here}../src/readiness-questions.js`,
  `// Generated by scripts/build-readiness-questions.mjs from readiness-check config.v1.json. Do not edit by hand.\nexport const READINESS = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`readiness questions: ${Object.keys(questions).length}, bands: ${Object.keys(out.bands).length}`);
